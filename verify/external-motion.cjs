// Real Electron: OS Open With queue, external annotation persistence and host motion.
// GENESIS_DESKTOP=<built desktop> node verify/external-motion.cjs (under devlock).
const fs = require('fs'), os = require('os'), path = require('path'), assert = require('node:assert/strict')
const HERE = path.resolve(__dirname, '..')
const DESK = process.env.GENESIS_DESKTOP
if (!DESK) throw new Error('Set GENESIS_DESKTOP to a built desktop checkout')
const electron = require(path.join(DESK, 'scripts/lib/launch-electron.cjs'))
const { startStubEngine } = require(path.join(DESK, 'scripts/lib/stub-engine.cjs'))
const { PDFDocument, StandardFonts } = require(path.join(HERE, 'node_modules/pdf-lib'))
const home = fs.mkdtempSync(path.join(os.tmpdir(), 'better-pdf-external-'))
const shots = path.join(HERE, '.shots', 'external-motion'); fs.mkdirSync(shots, { recursive: true })
const pdf = path.join(home, 'Downloads', 'Research paper.pdf')
const sidecar = path.join(path.dirname(pdf), '.Research paper.pdf.annot.json')
const userData = path.join(home, 'userdata')
const pause = (ms) => new Promise((r) => setTimeout(r, ms))
let passed = 0
function check(name, ok) { assert.ok(ok, name); console.log(`PASS ${name}`); passed++ }
async function until(fn, timeout = 8000) { const end = Date.now() + timeout; while (Date.now() < end) { if (await fn()) return; await pause(80) } throw new Error('Condition timed out') }
const saved = () => fs.existsSync(sidecar) ? JSON.parse(fs.readFileSync(sidecar, 'utf8')) : null
async function main() {
  fs.mkdirSync(path.dirname(pdf), { recursive: true })
  const doc = await PDFDocument.create(), font = await doc.embedFont(StandardFonts.Helvetica)
  for (let i = 0; i < 3; i++) { const p = doc.addPage([612, 792]); p.drawText('A paper opened from the operating system.', { x: 54, y: 710, size: 18, font }); p.drawText(`Evidence belongs beside the source. Page ${i + 1}.`, { x: 54, y: 670, size: 15, font }) }
  fs.writeFileSync(pdf, await doc.save()); const original = fs.readFileSync(pdf)
  const plug = path.join(home, 'plugins', 'better-pdf'); fs.mkdirSync(plug, { recursive: true })
  for (const f of ['main.js', 'manifest.json']) fs.copyFileSync(path.join(HERE, f), path.join(plug, f))
  for (const d of [userData, `${userData}-dev`]) { fs.mkdirSync(d, { recursive: true }); for (const f of ['amadeus-config.json', 'amadeus-config.dev.json']) fs.writeFileSync(path.join(d, f), JSON.stringify({ lastVault: '', localVault: '' })) }
  const stub = await startStubEngine()
  let app, win
  const errors = []
  try {
    app = await electron.launch({ args: [`--user-data-dir=${userData}`, '--lang=zh-CN', DESK, pdf], cwd: DESK,
      env: { ...process.env, TANGU_HOME: home, FORSION_WORKSPACE_DIR: path.join(home, 'Workspace'), TANGU_BACKEND_URL: stub.url, TANGU_HARNESS_QUIET: '1' } })
    win = await app.firstWindow(); win.on('pageerror', (e) => errors.push(String(e)))
    await app.evaluate(({ BrowserWindow }) => BrowserWindow.getAllWindows()[0].setContentSize(1512, 950))
    await win.waitForSelector('#root'); await pause(2500)
    for (const label of ['跳过引导', 'Skip']) { const b = win.getByText(label, { exact: true }).first(); if (await b.isVisible().catch(() => false)) { await b.click(); break } }
    await win.waitForSelector('.pr-root .textLayer span', { timeout: 30000 })
    check('cold-start Open With mounts Better PDF outside any vault', await win.locator('.pr-root .page').count() === 3 && await win.locator('.wsfile-view, .amx-pdfview').count() === 0)
    check('opening a PDF creates no empty annotation file', !fs.existsSync(sidecar))
    await win.evaluate(() => localStorage.setItem('forsion_ui_zoom', '1.1'))
    await win.reload(); await win.waitForSelector('.dv-groupview', { timeout: 30000 }); await pause(2000)
    // The exact Electron event Finder's Open With produces, delivered to this isolated app.
    const openSystem = () => app.evaluate(({ app }, p) => app.emit('open-file', { preventDefault() {} }, p), pdf)
    await openSystem(); await win.waitForSelector('.pr-root .textLayer span', { timeout: 30000 })
    await pause(800)
    check('warm system Open With uses the plugin at 110% UI zoom', await win.locator('.pr-root').count() >= 1)
    const root = () => win.locator('.pr-root').last()
    await root().locator('[data-act="tool"][data-v="highlight"]').click()
    const text = root().locator('.page[data-page-number="1"] .textLayer span').first()
    const b = await text.boundingBox()
    await win.mouse.move(b.x + 2, b.y + b.height / 2); await win.mouse.down(); await win.mouse.move(b.x + b.width - 2, b.y + b.height / 2, { steps: 12 }); await win.mouse.up()
    await until(() => saved()?.annots.length === 1)
    check('external highlight persists beside the PDF', saved().annots[0].type === 'highlight')
    await root().locator('[data-act="tool"][data-v="select"]').click(); await pause(400)
    const mark = await root().locator('.pr-hl').first().boundingBox()
    await win.mouse.click(mark.x + mark.width / 2, mark.y + mark.height / 2)
    const card = win.locator('.ui-popover .pr-card').first(); await card.waitFor({ state: 'visible' })
    check('annotation card uses the host popover', await card.getAttribute('data-hosted') !== null)
    await card.locator('textarea').fill('Draft while editing')
    await pause(120)
    const anchored = await card.boundingBox()
    check('editing keeps the card anchored below its annotation', anchored.y >= mark.y + mark.height - 2 && anchored.y < mark.y + mark.height + 40 && anchored.x > mark.x - 30)
    await win.screenshot({ path: path.join(shots, 'light-card.png') })
    const cardExit = await win.evaluate(() => {
      document.dispatchEvent(new KeyboardEvent('keydown', { key: 'Escape', bubbles: true }))
      const e = document.querySelector('.ui-popover[data-lcl-exit]')
      return e && { name: getComputedStyle(e).animationName, inert: e.inert }
    })
    check('host annotation card exits with an inert animated surface', cardExit?.name === 'ui-menu-exit' && cardExit.inert)
    await pause(150)
    await win.mouse.click(mark.x + mark.width / 2, mark.y + mark.height / 2)
    await card.waitFor({ state: 'visible' })
    await card.locator('textarea').fill('Last edit before closing the tab')
    // Close immediately, within the plugin's 400ms comment debounce.
    const closeTab = async () => {
      const tab = win.locator('.wb-tab').filter({ hasText: 'Research paper.pdf' }).last()
      await tab.locator('.wb-tab-close').click()
    }
    await closeTab()
    await until(() => saved()?.annots[0].comment === 'Last edit before closing the tab')
    check('closing immediately saves the final comment before access is revoked', saved().annots[0].comment === 'Last edit before closing the tab')
    await openSystem(); await win.waitForSelector('.pr-root .pr-hl', { timeout: 15000 })
    check('system reopen restores annotations', await root().locator('.pr-hl').count() >= 1)
    await root().locator('[data-act="tool"][data-v="note"]').click()
    const notePage = await root().locator('.page[data-page-number="1"]').boundingBox()
    await win.mouse.click(notePage.x + notePage.width - 60, notePage.y + 120)
    await pause(300)
    check('new note card receives keyboard focus', await win.evaluate(() => document.activeElement?.classList.contains('pr-card-body')))
    await win.keyboard.type('Note entered from the keyboard')
    await until(() => saved()?.annots.some((a) => a.type === 'note' && a.comment === 'Note entered from the keyboard'))
    check('new sticky note focuses its host card and saves keyboard input', true)
    await win.keyboard.press('Escape')
    const more = root().locator('[data-act="more"]')
    await more.click(); const menu = win.locator('.ctx-menu:not([data-lcl-exit])').last(); await menu.waitFor()
    const menuMotion = await menu.evaluate((e) => ({ name: getComputedStyle(e).animationName, duration: getComputedStyle(e).animationDuration }))
    check('More uses the host menu and enter animation', menuMotion.name === 'ui-menu-enter' && parseFloat(menuMotion.duration) > 0)
    await win.screenshot({ path: path.join(shots, 'light-menu.png') })
    await win.keyboard.press('Escape'); await pause(180)
    check('host menus finish their exit without an interactive remnant', await win.locator('.ctx-menu').count() === 0)
    await root().locator('[data-act="find"]').click()
    check('Find uses shared user-triggered enter motion', await root().locator('.pr-findbar').getAttribute('data-motion') === 'enter')
    await root().locator('[data-act="find-close"]').click()
    await root().locator('[data-act="thumbs"]').click()
    check('Thumbnails use shared user-triggered enter motion', await root().locator('.pr-side').getAttribute('data-motion') === 'enter')
    await root().locator('[data-act="tool"][data-v="ink"]').click()
    check('pen palette uses shared enter motion', await root().locator('.pr-palette').getAttribute('data-motion') === 'enter')
    await root().locator('[data-act="tool"][data-v="select"]').click()
    await win.mouse.move(5, 5); await more.hover(); await win.waitForSelector('.lcl-tip', { timeout: 3000 })
    check('toolbar tooltips use host timing and surfaces', await win.locator('.lcl-tip').count() > 0)
    await win.mouse.move(5, 5); await pause(300)
    await win.emulateMedia({ reducedMotion: 'reduce' }); await more.click()
    check('reduced motion disables menu entrance', await win.locator('.ctx-menu:not([data-lcl-exit])').last().evaluate((e) => getComputedStyle(e).animationName) === 'none')
    await win.keyboard.press('Escape'); await pause(200); await win.emulateMedia({ reducedMotion: 'no-preference' })
    const exported = path.join(home, 'Annotated copy.pdf')
    await app.evaluate(({ dialog }, dest) => { dialog.showSaveDialog = async () => ({ canceled: false, filePath: dest }) }, exported)
    await more.click(); await win.locator('.ctx-menu button').filter({ hasText: '导出带批注的 PDF' }).click()
    await until(() => fs.existsSync(exported))
    check('external export saves an annotated copy and leaves the source unchanged', fs.readFileSync(exported).includes(Buffer.from('/Highlight')) && fs.readFileSync(pdf).equals(original))
    await win.evaluate(() => { document.documentElement.setAttribute('data-mode', 'dark'); document.querySelectorAll('[data-mode]').forEach((el) => el.setAttribute('data-mode', 'dark')) })
    await more.click(); await win.screenshot({ path: path.join(shots, 'dark-menu.png') }); await win.keyboard.press('Escape')
    check('no renderer exceptions', errors.length === 0)
    fs.writeFileSync(path.join(shots, 'report.json'), JSON.stringify({ passed, errors, home, pdf, shots }, null, 2))
    console.log(`${passed} checks passed; screenshots: ${shots}`)
  } catch (e) {
    if (win) await win.screenshot({ path: path.join(shots, 'failure.png') }).catch(() => {})
    throw e
  } finally { await app?.close().catch(() => {}); await stub.close?.() }
}
main().catch((e) => { console.error(e); process.exitCode = 1 })
